"""
Per-target acceptance/rejection analysis for Keck/LRIS 2026-10-06
(Keck-2026B-02 pull).

Created by JXP and Claude

Walks every target in the Keck-2026B-02 FFFF-PZ pull through the same
filter stages keck_2026oct06_calculations.py uses, in order, and records
the numeric reason at the stage where each target drops out:

  1. Keck selection  (mag > 19, unless Dec > 82 deg Lick limit)
  2. Sky             (>= 30 min at airmass < 2.0, Keck pointing limits,
                      Keck I Nasmyth-deck vignetting)
  2b. Mask           (mag>21 target needs a mask in MOS_MASKS_AVAILABLE)
  3. Scheduling      (on-target time + Keck slew fits the target's AM<2.0
                      window and the night's time budget)

Writes Night_plans/Keck-2026B-02/target_rejection_analysis.md.
"""

import io
import re
from contextlib import redirect_stdout

import pandas as pd

from keck_2026oct06_calculations import (
    KECK_MAG_FAINT_LIMIT, LICK_DEC_LIMIT, analyze_targets,
    select_targets_for_night,
)
from keck_overheads import (
    KECK_SLEW_BASE_MIN, KECK_SLEW_DEC_CROSS_MIN, KECK_SLEW_DEC_BOUNDARY,
)
from night_planner.targets_io import load_targets

import sys
from pathlib import Path

# Repo-relative, so this runs wherever the checkout lives.
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from night_planner.paths import plans_dir

_PLANS = plans_dir()

RUN_DIR = f'{_PLANS}/Keck-2026B-02'
TARGETS_CSV = f'{RUN_DIR}/Keck-2026B-02_targets.csv'
DATE = '2026-10-06'
OUTFILE = f'{RUN_DIR}/target_rejection_analysis.md'


def run_pipeline():
    """
    Run the Keck analysis + scheduler, capturing the scheduler's skip lines.

    Returns
    -------
    pulled : DataFrame, the raw FFFF-PZ pull
    results_df : DataFrame, targets passing the Keck selection rule
    selected : DataFrame, scheduled targets
    skips : dict, TNS -> scheduler skip reason
    """
    pulled = load_targets(TARGETS_CSV)
    buf = io.StringIO()
    with redirect_stdout(buf):
        results_df, twilight, _ = analyze_targets(TARGETS_CSV, DATE)
        selected = select_targets_for_night(results_df, twilight, max_targets=20)
    skips = {}
    for line in buf.getvalue().splitlines():
        m = re.match(r'\s*Skipped (\S+): (.*)', line)
        if m:
            skips[m.group(1)] = m.group(2)
    return pulled, results_df, selected, skips


def classify(pulled, results_df, selected, skips):
    """
    Assign each pulled target a final status, stage and numeric reason.

    Returns
    -------
    list of dict with 'TNS', 'mag', 'dec', 'status', 'stage', 'reason'
    """
    rows = []
    res = results_df.set_index('TNS')
    sel = selected.set_index('TNS') if len(selected) else pd.DataFrame()
    for _, p in pulled.iterrows():
        tns, mag, dec = p['name'], p['mag'], p['dec_deg']
        out = {'TNS': tns, 'mag': mag, 'dec': dec}
        if tns not in res.index:
            out.update(status='REJECTED', stage='1. Keck selection',
                       reason=(f"mag {mag:.2f} <= {KECK_MAG_FAINT_LIMIT} and Dec "
                               f"{dec:+.1f} <= {LICK_DEC_LIMIT} (Lick can take it)"))
        elif res.loc[tns, 'limit_reason'].startswith('No mask'):
            out.update(status='REJECTED', stage='2b. Mask',
                       reason=res.loc[tns, 'limit_reason'])
        elif not res.loc[tns, 'observable']:
            r = res.loc[tns]
            out.update(status='REJECTED', stage='2. Sky',
                       reason=(f"{r['limit_reason']} (min AM {r['min_airmass']:.2f}, "
                               f"{r['observable_hours']:.2f} h at AM<2.0; need >0.5 h)"))
        elif len(sel) and tns in sel.index:
            s = sel.loc[tns]
            out.update(status='SCHEDULED', stage='3. Scheduling',
                       reason=(f"slew {s['scheduled_start'].strftime('%H:%M')} "
                               f"({int(s['slew_min'])} min), on target "
                               f"{s['science_start'].strftime('%H:%M')}-"
                               f"{s['scheduled_end'].strftime('%H:%M')} HST "
                               f"({s['on_target_min']:g} min, {s['lris_mode']}); "
                               f"window {s['window_start'].strftime('%H:%M')}-"
                               f"{s['window_end'].strftime('%H:%M')}"))
        else:
            out.update(status='REJECTED', stage='3. Scheduling',
                       reason=skips.get(tns, 'not reached (max_targets hit)'))
        rows.append(out)
    return rows


def write_markdown(rows, selected):
    """Write the summary table and per-target detail to OUTFILE."""
    n_sched = sum(r['status'] == 'SCHEDULED' for r in rows)
    lines = [
        '# Keck/LRIS 2026-10-06 — per-target accept/reject analysis',
        '',
        'Created by JXP and Claude (generated by '
        '`scripts/keck_2026oct06_rejection_analysis.py`).',
        '',
        f'{len(rows)} targets pulled, {n_sched} scheduled. Slew rule: '
        f'{KECK_SLEW_BASE_MIN} min base, {KECK_SLEW_DEC_CROSS_MIN} min when moving '
        f'from Dec < +{KECK_SLEW_DEC_BOUNDARY:.0f} to Dec > +{KECK_SLEW_DEC_BOUNDARY:.0f} '
        f'(`scripts/keck_overheads.py`). Total slew: '
        f'{int(selected["slew_min"].sum()) if len(selected) else 0} min.',
        '',
        '## Summary',
        '',
        '| TNS | mag | Dec | Status | Stage | Reason |',
        '|-----|-----|-----|--------|-------|--------|',
    ]
    for r in rows:
        lines.append(f"| {r['TNS']} | {r['mag']:.1f} | {r['dec']:+.1f} | "
                     f"{r['status']} | {r['stage']} | {r['reason']} |")
    lines += ['', '## Per-target detail', '']
    for r in rows:
        lines += [f"### {r['TNS']} — {r['status']}", '',
                  f"- mag_r {r['mag']:.2f}, Dec {r['dec']:+.2f}",
                  f"- Dropped/decided at: {r['stage']}",
                  f"- {r['reason']}", '']
    with open(OUTFILE, 'w') as f:
        f.write('\n'.join(lines))
    print(f'Wrote {OUTFILE}')


def main():
    """Run the analysis and write the markdown report."""
    pulled, results_df, selected, skips = run_pipeline()
    rows = classify(pulled, results_df, selected, skips)
    write_markdown(rows, selected)


if __name__ == '__main__':
    main()
